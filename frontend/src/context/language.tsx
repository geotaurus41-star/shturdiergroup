const LanguageContext = createContext<{ language: Language; setLanguage: (language: Language) => void; t: (text: string) => string }>({
  language: 'ENG',
  setLanguage: () => undefined,
  t: (text) => text,
});

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>(() => {
    const stored = localStorage.getItem('silver-language');
    return stored === 'GEO' ? 'GEO' : 'ENG';
  });
  const setLanguage = (value: Language) => {
    localStorage.setItem('silver-language', value);
    setLanguageState(value);
  };
  const t = (text: string) => language === 'GEO' ? translations[text] ?? text : text;
  useEffect(() => {
    document.documentElement.lang = language === 'GEO' ? 'ka' : 'en';
  }, [language]);
  return <LanguageContext.Provider value={{ language, setLanguage, t }}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  return useContext(LanguageContext);
}
